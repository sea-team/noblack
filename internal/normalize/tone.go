package normalize

// 拼音声调折叠。
//
// 黑产会用带声调的拼音绕过词库: "怎么做zha yào" —— 去掉空格后是 "zhayào",
// 与词条 "炸药" 及其拼音 "zhayao" 都对不上。把 à→a、ǐ→i 折叠掉之后,
// 才能进一步做拼音匹配。
//
// 只做 1:1 的 rune 映射, 不改变字符数量, 因此不影响 Normalize 的索引映射。
// 注意 unicode.IsMark 会剔除组合式声调 (a + U+0300), 这里处理的是
// 预组合字符 (U+00E0 à) —— 输入法和复制粘贴产出的通常是后者。

// toneFolded 把带声调的拉丁字母还原为基本字母。
//
// 覆盖汉语拼音实际会用到的字符:
//   - a e i o u 的四声 (ā á ǎ à 等)
//   - ü 及其四声 (ü ǖ ǘ ǚ ǜ) → v, 保留 v/u 两种写法由调用方决定
//   - ê 的声调形式
//   - n m 的声调形式 (ń ň ǹ, 用于 "嗯" 之类的拟声)
//   - ɡ (U+0261 拉丁小写脚本 g) → g, 部分输入法与字体会产出这个变体
var toneFolded = map[rune]rune{
	// a
	'ā': 'a', 'á': 'a', 'ǎ': 'a', 'à': 'a', 'â': 'a', 'ä': 'a', 'ã': 'a', 'å': 'a', 'ạ': 'a',
	// e
	'ē': 'e', 'é': 'e', 'ě': 'e', 'è': 'e', 'ê': 'e', 'ë': 'e', 'ẽ': 'e', 'ẹ': 'e',
	'ế': 'e', 'ề': 'e', 'ể': 'e', 'ễ': 'e',
	// i
	'ī': 'i', 'í': 'i', 'ǐ': 'i', 'ì': 'i', 'î': 'i', 'ï': 'i', 'ĩ': 'i', 'ị': 'i',
	// o
	'ō': 'o', 'ó': 'o', 'ǒ': 'o', 'ò': 'o', 'ô': 'o', 'ö': 'o', 'õ': 'o', 'ọ': 'o',
	// u
	'ū': 'u', 'ú': 'u', 'ǔ': 'u', 'ù': 'u', 'û': 'u', 'ũ': 'u', 'ụ': 'u',
	// ü 系列: 拼音里 ü 常写作 v (lv = lü), 统一折叠为 v 以便与键盘输入对齐
	'ü': 'v', 'ǖ': 'v', 'ǘ': 'v', 'ǚ': 'v', 'ǜ': 'v',
	// n m (ḿ 用于拟声词)
	'ń': 'n', 'ň': 'n', 'ǹ': 'n', 'ñ': 'n',
	'ḿ': 'm',
	// 字形变体
	'ɡ': 'g', // U+0261 LATIN SMALL LETTER SCRIPT G
	'ɑ': 'a', // U+0251 LATIN SMALL LETTER ALPHA
}

// foldTone 折叠声调符号; 非声调字符原样返回。
func foldTone(r rune) rune {
	if folded, ok := toneFolded[r]; ok {
		return folded
	}
	return r
}
